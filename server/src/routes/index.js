import { Router } from 'express';
import api from '../controllers/api.js';
import { requireAuth, requireRole } from '../middleware/auth.js';
import * as auth from '../controllers/auth.js';
import * as catalogue from '../controllers/catalogue.js';
import { validate } from '../middleware/validate.js';
import { addressSchema, cancelOrderSchema, cartItemSchema, categorySchema, checkoutSchema, couponSchema, forgotPasswordSchema, loginSchema, orderListSchema, paymentRetrySchema, productIdsSchema, productPatchSchema, productQuerySchema, productSchema, profileSchema, quantitySchema, registerSchema, resetPasswordSchema, statusSchema } from '../validators/schemas.js';
import * as commerce from '../controllers/commerce.js';
import rateLimit from 'express-rate-limit';

const router = Router();
const authLimit = () => rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, standardHeaders: 'draft-7', legacyHeaders: false, skip: () => process.env.NODE_ENV === 'test' });
const checkoutLimit = () => rateLimit({ windowMs: 15 * 60 * 1000, limit: 12, standardHeaders: 'draft-7', legacyHeaders: false, skip: () => process.env.NODE_ENV === 'test' });
router.post('/auth/register', authLimit(), validate(registerSchema), auth.register);
router.post('/auth/login', authLimit(), validate(loginSchema), auth.login);
router.get('/auth/me', requireAuth, auth.me);
router.post('/auth/forgot-password', authLimit(), validate(forgotPasswordSchema), auth.forgotPassword);
router.post('/auth/reset-password/:token', validate(resetPasswordSchema), auth.resetPassword);
router.get('/users/me', requireAuth, api.profile);
router.patch('/users/me', requireAuth, validate(profileSchema), api.updateProfile);
router.get('/addresses', requireAuth, commerce.listAddresses);
router.post('/addresses', requireAuth, validate(addressSchema), commerce.addAddress);
router.put('/addresses/:id', requireAuth, validate(addressSchema), commerce.updateAddress);
router.patch('/addresses/:id', requireAuth, validate(addressSchema), commerce.updateAddress);
router.delete('/addresses/:id', requireAuth, commerce.deleteAddress);
router.patch('/addresses/:id/default', requireAuth, commerce.setDefaultAddress);
router.get('/categories', catalogue.categories);
router.post('/admin/categories', requireAuth, requireRole('admin'), validate(categorySchema), api.createCategory);
router.patch('/admin/categories/:id', requireAuth, requireRole('admin'), validate(categorySchema), api.updateCategory);
router.get('/products', validate(productQuerySchema, 'query'), catalogue.products);
router.get('/products/by-ids', validate(productIdsSchema, 'query'), catalogue.productsByIds);
router.get('/products/:slug', catalogue.productBySlug);
router.get('/cart', requireAuth, api.getCart);
router.post('/cart/items', requireAuth, validate(cartItemSchema), api.addCartItem);
router.patch('/cart/items/:productId/:variantId?', requireAuth, validate(quantitySchema), api.updateCartItem);
router.delete('/cart/items/:productId/:variantId?', requireAuth, api.removeCartItem);
router.post('/cart/coupon', requireAuth, validate(couponSchema), api.applyCoupon);
router.delete('/cart/coupon', requireAuth, api.removeCoupon);
router.post('/orders/checkout', requireAuth, checkoutLimit(), validate(checkoutSchema), commerce.checkout);
router.get('/orders', requireAuth, validate(orderListSchema, 'query'), commerce.listOrders);
router.get('/orders/:id', requireAuth, commerce.getOrder);
router.post('/orders/:id/pay-retry', requireAuth, checkoutLimit(), validate(paymentRetrySchema), commerce.retryPayment);
router.post('/orders/:id/cancel', requireAuth, validate(cancelOrderSchema), commerce.cancelOrder);
router.get('/admin/dashboard', requireAuth, requireRole('admin'), api.dashboard);
router.get('/admin/customers', requireAuth, requireRole('admin'), api.customers);
router.post('/admin/products', requireAuth, requireRole('admin'), validate(productSchema), api.createProduct);
router.patch('/admin/products/:id', requireAuth, requireRole('admin'), validate(productPatchSchema), api.updateProduct);
router.delete('/admin/products/:id', requireAuth, requireRole('admin'), api.deleteProduct);
router.patch('/admin/orders/:id/status', requireAuth, requireRole('admin'), validate(statusSchema), api.setOrderStatus);
router.get('/audit-logs', requireAuth, requireRole('admin'), api.auditLogs);
export default router;
